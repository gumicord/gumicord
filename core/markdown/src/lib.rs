//! Discord の Markdown を読む (`FR-021`)。
//!
//! # ⚠️ これは CommonMark ではない
//!
//! 見た目が似ているので取り違えやすいが、別物である。`pulldown-cmark` などの
//! 出来合いを持ってくると、**Discord にある記法が落ち、無い記法が増える**。
//!
//! | Discord にあって CommonMark に無い | CommonMark にあって Discord に無い |
//! |---|---|
//! | `__下線__` (CommonMark では太字) | 参照リンク `[a][b]` |
//! | `\|\|スポイラー\|\|` | 字下げ 4 つのコードブロック |
//! | `-# 小さい注釈` | `#### ` 以下の見出し |
//! | `~~打ち消し~~` (GFM 側) | HTML の直書き |
//! | `<@123>` `<#123>` `<:名前:123>` | 表・脚注 |
//! | `> ` に加えて `>>> ` (以降ぜんぶ) | 水平線 `---` |
//!
//! 更に、同じ記法でも境目の規則が違う。`a * b * c` を Discord は斜体にせず、
//! `snake_case_word` も斜体にしない ([`inline`] に規則を書いてある)。
//!
//! # 何を返すか
//!
//! [`Block`] の並びだけを返す。**色も大きさも決めない。**
//! 「太字である」までがここの仕事で、太字を何ポイントで描くかはテーマが
//! 決める ([`spec/04-theme.md`])。
//!
//! ⚠️ **名前も解決しない。** `<@123>` から返るのは番号だけである。
//! 誰かを知っているのは手元の一覧であって、文字列の解析ではない。
//!
//! # 壊れた入力で落ちない
//!
//! 本文は他人が打った文字列である。閉じない `**`、終わらない ```` ``` ````、
//! 桁の溢れる `99999999999.`、深く入れ子にした `>` が**普通に来る**。
//!
//! ⚠️ **読めなかった記法は、打たれたとおりの文字として出す。** 捨てると
//! 本文が黙って消える。これは誤読より悪い — 読み手は消えたことに気づけない。
//!
//! 要件: `FR-021`, `FR-022`, `FR-023`
//! 仕様: [`spec/03-uitree.md`] 8 (Markdown をどこまでノードにするか)

mod block;
mod inline;
mod model;

pub use model::{Block, Deco, Inline, InlineKind, Item, Marker, Mention};

/// 本文を読む。**空文字列からは空が返る。**
pub fn parse(text: &str) -> Vec<Block> {
    block::parse(text)
}

/// 行の中だけを読む。見出しの中身のように、既に行が決まっているときに使う
pub fn parse_inline(text: &str) -> Vec<Inline> {
    inline::parse(text)
}

